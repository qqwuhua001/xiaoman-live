/* 同一个问题连着被问，别总是同一句：记住上次用的索引，下次换另一句 */
const lastPick = new Map();

/** 命中就返回一句现成台词，没命中返回空串（交回模型）。 */
export function quickReply(text) {
  const t = String(text || '');
  if (!t) return '';
  for (const r of RULES) {
    if (!r.re.test(t)) continue;
    const n = r.lines.length;
    if (n <= 1) return r.lines[0];
    const prev = lastPick.get(r.id);
    let i = Math.floor(Math.random() * n);
    if (i === prev) i = (i + 1) % n;
    lastPick.set(r.id, i);
    return r.lines[i];
  }
  return '';
}
